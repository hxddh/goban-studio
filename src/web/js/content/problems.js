/**
 * Practice problems (tsumego and tactics) for Goban Studio.
 *
 * Every problem is a real position checked by the solver (src/web/js/solver.js):
 * scripts/check-problems.mjs proves each one has between one and three correct
 * first moves, that the solver's answer line wins, and that no two problems
 * are the same position under rotation, reflection or colour swap. Difficulty
 * grades are measured by the solver, not assigned by hand; they are stored in
 * problem-grades.json by scripts/grade-problems.mjs.
 *
 * Diagram notation (see solver.js): X/O black/white stones, x/o key stones
 * (the stones the goal is about), '.' empty points in the problem region,
 * ',' empty points outside it. Black always moves first.
 *
 * Every problem names one `theme` from THEMES (the idea the answer turns
 * on). `ko: "ok"` marks a problem whose best result is a ko (theme "ko");
 * the solver proves no unconditional answer exists. `escape: 3` keeps the
 * beginner rule that three liberties count as escaped where the stones would
 * otherwise be lost to a slower chase the problem is not about.
 *
 * Goals (see createPuzzle in solver.js): "capture" / "save" the key stones,
 * "kill" / "live" a group in its region, and "seki": the learner defends the
 * key stones and the best result is seki. A seki problem carries the "seki"
 * theme (and only seki problems do); the solver proves that the stones
 * survive, that no defence gives them independent life (two eyes), and that
 * the answer ends in a real seki. A "live" problem still counts seki as
 * survival, and a "kill" that only reaches seki is a failure, as under
 * Japanese rules. Every ko counts against the learner unless `ko: "ok"`, so
 * bent four in the corner (dead under Japanese rules) is never accepted as
 * life, and no problem relies on it.
 *
 * Real-board rules: a captured point can be played again (the solver's
 * `replay`, on for every problem), and the key stones of a life or kill
 * problem must be sealed in, so they can never breathe through a ','
 * point nobody may fill. docs/problems-audit.md records the v4 audit that
 * fixed or removed the problems that relied on either.
 *
 * `shape` (optional) names the classic textbook shape a problem is built
 * on, from SHAPES; the app can list them as a collection.
 *
 * Endgame problems (v6, topic "endgame", goal "endgame") are proved by the
 * solver's counting mode (see the counting section of solver.js): exact
 * minimax counting of a sealed region under Japanese counting. Their
 * diagrams add ':' points, empty points that are counted at the end but not
 * played (the inside of a territory). `ask: "move"` asks for the biggest
 * move; `answer` (diagram coordinates) and `margin` (points gained over the
 * best other choice) are proved by the check. `ask: "value"` asks how many
 * points the move is worth; `value` is the proved deiri count and `choices`
 * the values the app offers.
 */

